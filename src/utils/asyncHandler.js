/*
 * Wraps async controllers to handle errors automatically.
 * If a controller's Promise rejects, catch the error and pass it to Express error-handling middleware using next(err)
*/


const asyncHandler = (requestHandler) => {
    return (req, res, next) => {
        Promise.resolve(requestHandler(req, res, next))
        .catch((err) => next(err))
    }
}


export {asyncHandler}

